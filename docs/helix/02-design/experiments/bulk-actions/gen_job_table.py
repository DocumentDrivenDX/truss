#!/usr/bin/env python3
"""Generate BulkUpdateJobTable.tla from the UMF owner fixture (transitions.json).
Allowed = {<<from, to, committedDelta>>} over fixture transitions whose expectation is ok.
Usage: gen_job_table.py --fixture F [--check]   (--check fails if the committed module differs)."""
import argparse, hashlib, json
from pathlib import Path
a = argparse.ArgumentParser(); a.add_argument('--fixture', required=True); a.add_argument('--check', action='store_true'); a = a.parse_args()
raw = Path(a.fixture).read_bytes(); fx = json.loads(raw); T = set()
for c in fx['transitions']:
    e = c['expect']
    if e.get('ok') and c['state'] is not None:
        s0, s1 = c['state'], e['state']
        T.add((s0['status'], s1['status'], s1.get('committedBatches', s0['committedBatches']) - s0['committedBatches']))
body = ',\n  '.join('<<"%s", "%s", %d>>' % t for t in sorted(T))
text = ('---- MODULE BulkUpdateJobTable ----\n\\* GENERATED by gen_job_table.py from UMF docs/helix/03-test/fixtures/bulk-update/transitions.json; do not edit.\n'
        '\\* fixture sha256: %s (status: %s)\nEXTENDS Integers\nAllowed == {\n  %s\n}\n====\n' % (hashlib.sha256(raw).hexdigest(), fx['status'], body))
out = Path(__file__).resolve().parent / 'BulkUpdateJobTable.tla'
if a.check: assert out.read_text() == text, 'BulkUpdateJobTable.tla is stale vs fixture'
else: out.write_text(text)
print('ok', len(T), 'triples')
