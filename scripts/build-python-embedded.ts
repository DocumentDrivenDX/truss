// Build-time only: preserve owner source bytes and compile their module syntax.
import ts from 'typescript-compiler';
import {gzipSync} from 'node:zlib';
import {readdir,readFile,writeFile} from 'node:fs/promises';
import {join,dirname} from 'node:path';
import {createHash} from 'node:crypto';
const root=join(import.meta.dir,'../packages/python/src/truss');
const cohorts=['_umf','_umf_core08','_umf_keys','_umf_keys08','_current_query_owner','_current_disclosure_owner','_preparation_sources'];
const modules:Record<string,string>={}, sources:Record<string,string>={}, hashes:Record<string,string>={};
async function walk(dir:string){for(const item of await readdir(join(root,dir),{withFileTypes:true})){
 const path=dir+'/'+item.name;if(item.isDirectory()){await walk(path);continue;}
 if(!/\.(m?js|json)$/.test(path))continue;
 const raw=await readFile(join(root,path));sources[path]=raw.toString('base64');hashes[path]=createHash('sha256').update(raw).digest('hex');
 if(!/\.m?js$/.test(path))continue;
 const source=raw.toString('utf8');
 const code=source.startsWith('// @bun @bun-cjs')?source+'(exports, require, module, __filename, __dirname);':source;
 const transformed=ts.transpileModule(code,{fileName:path+'.ts',compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS},transformers:{before:[context=>file=>{
  function visit(node:ts.Node):ts.VisitResult<ts.Node>{
   if(ts.isIfStatement(node)&&ts.isPropertyAccessExpression(node.expression)&&ts.isMetaProperty(node.expression.expression)&&node.expression.name.text==='main'){
    const body=ts.visitEachChild(node.thenStatement,visit,context) as ts.Block;
    const arrow=ts.factory.createArrowFunction([ts.factory.createModifier(ts.SyntaxKind.AsyncKeyword)],undefined,[],undefined,ts.factory.createToken(ts.SyntaxKind.EqualsGreaterThanToken),body);
    return ts.factory.createIfStatement(ts.factory.createIdentifier('__main'),ts.factory.createReturnStatement(ts.factory.createCallExpression(ts.factory.createParenthesizedExpression(arrow),undefined,[])));
   }
   if(ts.isPropertyAccessExpression(node)&&ts.isMetaProperty(node.expression)){
    const name=node.name.text;
    if(name==='url')return ts.factory.createStringLiteral('file:///truss/'+path);
    if(name==='dir')return ts.factory.createStringLiteral('/truss/'+dirname(path));
    if(name==='require')return ts.factory.createIdentifier('require');
    if(name==='main')return ts.factory.createIdentifier('__main');
    throw Error('Unsupported import.meta '+name);
   }
   return ts.visitEachChild(node,visit,context);
  }return ts.visitNode(file,visit) as ts.SourceFile;
 }]}}).outputText;
 // Top-level await is valid only in the entry wrapper. All imported owner libraries are synchronous.
 modules[path]=transformed;
}}
for(const cohort of cohorts)await walk(cohort);
const output=join(root,'_embedded_js');
await writeFile(join(output,'modules.json.gz'),gzipSync(JSON.stringify({modules,sources}),{level:9}));
await writeFile(join(output,'sources.json'),JSON.stringify(hashes,null,2)+'\n');
const built=await Bun.build({entrypoints:[join(import.meta.dir,'embedded-polyfills.ts')],target:'browser',format:'iife',minify:false});
if(!built.success)throw new AggregateError(built.logs);
const polyfills=await built.outputs[0].text();
await writeFile(join(output,'polyfills.js'),polyfills);
const licenses:Record<string,unknown>={};
for(const match of polyfills.matchAll(/^  \/\/ (node_modules\/\.bun\/[^/]+\/node_modules\/(?:@[^/]+\/)?[^/]+)\//gm)){
 const directory=match[1];if(licenses[directory])continue;
 const metadata=JSON.parse(await readFile(join(root,'../../../..',directory,'package.json'),'utf8'));
 const texts:Record<string,string>={};for(const name of await readdir(join(root,'../../../..',directory)))if(/^(license|copying|notice)/i.test(name)){
  try{texts[name]=await readFile(join(root,'../../../..',directory,name),'utf8');}catch{}
 }
 if(!Object.keys(texts).length)throw Error('Missing bundled license '+directory);
 licenses[directory]={name:metadata.name,version:metadata.version,license:metadata.license,texts};
}
await writeFile(join(output,'licenses.json'),JSON.stringify(licenses,null,2)+'\n');
const assets=['modules.json.gz','sources.json','polyfills.js','runtime.js','licenses.json'];
const manifest:Record<string,string>={};for(const path of assets)manifest[path]=createHash('sha256').update(await readFile(join(output,path))).digest('hex');
await writeFile(join(output,'manifest.json'),JSON.stringify({profile:'truss.embedded-v8/1',engine:'mini-racer==0.14.1',files:manifest},null,2)+'\n');
await writeFile(join(root,'_embedded_release.py'), '# Generated by scripts/build-python-embedded.ts\nMANIFEST_SHA256 = '+JSON.stringify(createHash('sha256').update(await readFile(join(output,'manifest.json'))).digest('hex'))+'\n');
console.log(`Embedded ${Object.keys(modules).length} original modules; ${Object.keys(sources).length} source assets`);
